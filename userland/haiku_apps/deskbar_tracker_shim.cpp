void InitIconPreloader()
{
    BResources* res = new BResources();
    res->AddResource(B_VECTOR_ICON_TYPE, R_LeafLogoBitmap,
                     kLeafLogoVectorIcon, sizeof(kLeafLogoVectorIcon),
                     "R_LeafLogoBitmap");
    res->AddResource(B_VECTOR_ICON_TYPE, R_TeamIcon,
                     kTeamVectorIcon, sizeof(kTeamVectorIcon),
                     "R_TeamIcon");
    res->AddResource(B_VECTOR_ICON_TYPE, R_WindowShownIcon,
                     kWindowShownVectorIcon, sizeof(kWindowShownVectorIcon),
                     "R_WindowShownIcon");
    res->AddResource(B_VECTOR_ICON_TYPE, R_WindowHiddenIcon,
                     kWindowHiddenVectorIcon, sizeof(kWindowHiddenVectorIcon),
                     "R_WindowHiddenIcon");
    res->AddResource(B_VECTOR_ICON_TYPE, R_WindowShownSwitchIcon,
                     kWindowShownSwitchVectorIcon, sizeof(kWindowShownSwitchVectorIcon),
                     "R_WindowShownSwitchIcon");
    res->AddResource(B_VECTOR_ICON_TYPE, R_WindowHiddenSwitchIcon,
                     kWindowHiddenSwitchVectorIcon, sizeof(kWindowHiddenSwitchVectorIcon),
                     "R_WindowHiddenSwitchIcon");
    AppResSet()->AddResources(res);

    pthread_t watcherTid;
    if (pthread_create(&watcherTid, nullptr, DeskbarWindowTeamWatcherThread, nullptr) == 0) {
        pthread_detach(watcherTid);
    }
}

