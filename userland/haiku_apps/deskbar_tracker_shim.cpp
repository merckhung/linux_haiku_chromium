static void* DeskbarWindowTeamWatcherThread(void* /*arg*/)
{
    std::set<team_id> knownTeams;
    pid_t selfPid = getpid();

    // Wait briefly for TBarApp to finish initializing its window
    usleep(500000);

    while (be_app != nullptr) {
        int32 count = 0;
        int32* tokens = get_token_list(-1, &count);
        std::set<team_id> currentTeams;

        if (tokens != nullptr) {
            for (int32 i = 0; i < count; i++) {
                client_window_info* wInfo = get_window_info(tokens[i]);
                if (wInfo == nullptr)
                    continue;
                team_id team = wInfo->team;
                free(wInfo);

                if (team <= 1 || team == selfPid)
                    continue;
                currentTeams.insert(team);
            }
            free(tokens);
        }

        // Notify newly discovered GUI teams
        for (team_id team : currentTeams) {
            if (knownTeams.find(team) == knownTeams.end()) {
                char linkPath[64];
                char exePath[B_PATH_NAME_LENGTH];
                snprintf(linkPath, sizeof(linkPath), "/proc/%d/exe", (int)team);
                ssize_t len = readlink(linkPath, exePath, sizeof(exePath) - 1);
                if (len <= 0)
                    continue;
                exePath[len] = '\0';

                // Ignore app_server itself
                if (strstr(exePath, "app_server") != nullptr ||
                    strstr(exePath, "Deskbar") != nullptr) {
                    knownTeams.insert(team);
                    continue;
                }

                const char* baseName = strrchr(exePath, '/');
                baseName = baseName ? (baseName + 1) : exePath;
                const char* displayName = (strcmp(baseName, "chrome") == 0)
                    ? "Chromium" : baseName;

                entry_ref ref;
                if (get_ref_for_path(exePath, &ref) != B_OK) {
                    ref = entry_ref(1, 1, displayName);
                } else {
                    ref.set_name(displayName);
                }
                char sig[B_MIME_TYPE_LENGTH];
                snprintf(sig, sizeof(sig), "application/x-vnd.%s", baseName);

                BMessage launchMsg(B_SOME_APP_LAUNCHED);
                launchMsg.AddInt32("be:team", team);
                launchMsg.AddInt32("be:flags", B_MULTIPLE_LAUNCH);
                launchMsg.AddString("be:signature", sig);
                launchMsg.AddRef("be:ref", &ref);
                be_app->PostMessage(&launchMsg);
                knownTeams.insert(team);
            }
        }

        // Notify teams that have exited
        for (auto it = knownTeams.begin(); it != knownTeams.end();) {
            team_id team = *it;
            if (kill(team, 0) != 0 && currentTeams.find(team) == currentTeams.end()) {
                BMessage quitMsg(B_SOME_APP_QUIT);
                quitMsg.AddInt32("be:team", team);
                be_app->PostMessage(&quitMsg);
                it = knownTeams.erase(it);
            } else {
                ++it;
            }
        }

        usleep(400000);
    }
    return nullptr;
}

